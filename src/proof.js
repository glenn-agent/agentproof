import { readDiffSummary, readGitState } from './git.js';

export function buildChecklist(gitState) {
  const checks = [];

  checks.push({
    ok: gitState.clean,
    label: gitState.clean ? 'Working tree is clean' : 'Working tree has local changes',
  });

  if (gitState.upstream) {
    checks.push({
      ok: gitState.behind === 0,
      label: gitState.behind === 0
        ? `Branch is not behind ${gitState.upstream}`
        : `Branch is ${gitState.behind} commit(s) behind ${gitState.upstream}`,
    });
    checks.push({
      ok: true,
      label: gitState.ahead === 0
        ? `No unpushed commits relative to ${gitState.upstream}`
        : `${gitState.ahead} commit(s) ahead of ${gitState.upstream}`,
    });
  } else {
    checks.push({ ok: false, label: 'No upstream branch configured' });
  }

  return checks;
}

export function renderMarkdown({ gitState, diffSummary, commands = [] }) {
  const lines = [];
  lines.push('## AgentProof');
  lines.push('');
  lines.push('### Repository');
  lines.push('');
  lines.push(`- Root: \`${gitState.root}\``);
  lines.push(`- Branch: \`${gitState.branch}\``);
  lines.push(`- HEAD: \`${gitState.head}\``);
  if (gitState.upstream) {
    lines.push(`- Upstream: \`${gitState.upstream}\` (${gitState.ahead} ahead / ${gitState.behind} behind)`);
  } else {
    lines.push('- Upstream: _not configured_');
  }
  lines.push('');

  lines.push('### Preflight');
  lines.push('');
  for (const check of buildChecklist(gitState)) {
    lines.push(`- ${check.ok ? '✅' : '⚠️'} ${check.label}`);
  }
  lines.push('');

  if (diffSummary.files.length > 0 || diffSummary.staged || diffSummary.unstaged) {
    lines.push('### Changed files');
    lines.push('');
    for (const file of diffSummary.files) {
      lines.push(`- \`${file}\``);
    }
    if (diffSummary.files.length === 0) {
      lines.push('- _No tracked file diff against HEAD_');
    }
    lines.push('');

    if (diffSummary.staged) {
      lines.push('<details><summary>Staged diff stat</summary>');
      lines.push('');
      lines.push('```');
      lines.push(diffSummary.staged);
      lines.push('```');
      lines.push('</details>');
      lines.push('');
    }

    if (diffSummary.unstaged) {
      lines.push('<details><summary>Unstaged diff stat</summary>');
      lines.push('');
      lines.push('```');
      lines.push(diffSummary.unstaged);
      lines.push('```');
      lines.push('</details>');
      lines.push('');
    }
  }

  if (commands.length > 0) {
    lines.push('### Verification commands');
    lines.push('');
    for (const command of commands) {
      lines.push(`- \`${command}\``);
    }
    lines.push('');
  }

  lines.push('> Generated by AgentProof. Review before pasting into a PR.');
  lines.push('');

  return lines.join('\n');
}

export function generateProof({ cwd = process.cwd(), commands = [] } = {}) {
  const gitState = readGitState(cwd);
  const diffSummary = readDiffSummary(cwd);
  return renderMarkdown({ gitState, diffSummary, commands });
}
